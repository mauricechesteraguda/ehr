    challenge = SmsRecoveryChallenge.objects.get(pk=response.json()["recovery_id"])
    monkeypatch.setattr("backend.users.views.audit.append_audit_event", lambda **kwargs: (_ for _ in ()).throw(RuntimeError("audit unavailable")))
