@pytest.mark.django_db
def test_TC_EXP_0093_sms_recovery_is_rate_limited_expiring_and_single_use(client, settings):
    user = _user("tc-0093", role="patient")
    user.recovery_phone_hash = hashlib.sha256(b"5550100").hexdigest()
    user.save(update_fields=["recovery_phone_hash"])
    response = client.post("/api/auth/recovery/request/", {"username": user.username, "password": "pw", "phone": "5550100"})
    assert response.status_code == 200 and "code" not in response.json()
    for _ in range(2):
        assert client.post("/api/auth/recovery/request/", {"username": user.username, "password": "pw", "phone": "5550100"}).status_code == 200
    assert client.post("/api/auth/recovery/request/", {"username": user.username, "password": "pw", "phone": "5550100"}).status_code == 429
    challenge = SmsRecoveryChallenge.objects.get(pk=response.json()["recovery_id"])
    code = hashlib.sha256(f"{user.pk}:{user.username}".encode()).hexdigest()[:6]
    assert client.post("/api/auth/recovery/verify/", {"recovery_id": challenge.pk, "code": code}).status_code == 200
    assert client.post("/api/auth/recovery/verify/", {"recovery_id": challenge.pk, "code": code}).status_code == 400
    challenge = SmsRecoveryChallenge.objects.create(user=user, code_hash=hashlib.sha256(b"x").hexdigest(), expires_at=timezone.now(), delivery_reference="sms-test")
    assert client.post("/api/auth/recovery/verify/", {"recovery_id": challenge.pk, "code": "x"}).status_code == 400


@pytest.mark.django_db
def test_TC_EXP_0094_recovery_invalidates_mfa_state(client):
    user = _user("tc-0094", role="patient")
    user.recovery_phone_hash = hashlib.sha256(b"5550100").hexdigest()
    user.save(update_fields=["recovery_phone_hash"])
    _mfa_login(client, user)
    generation = user.mfa_generation
    request = client.post("/api/auth/recovery/request/", {"username": user.username, "password": "pw", "phone": "5550100"})
    challenge = SmsRecoveryChallenge.objects.get(pk=request.json()["recovery_id"])
    code = hashlib.sha256(f"{user.pk}:{user.username}".encode()).hexdigest()[:6]
    assert client.post("/api/auth/recovery/verify/", {"recovery_id": challenge.pk, "code": code}).status_code == 200
    user.refresh_from_db()
    assert user.mfa_generation == generation + 1 and not user.totp_enrolled
    assert client.get("/api/auth/session/").status_code in {401, 403}


